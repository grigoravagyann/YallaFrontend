import type { StaffAuth } from '../auth/staffEndpoints';
import { staffRoleToUserRole } from '../auth/endpoints';
import {
  DeviceRevokedError,
  EnrolmentCodeExpiredError,
  EnrolmentCodeSpentError,
  KitchenPhoneNotAllowedError,
  PairingCodeExpiredError,
  PairingCodeInvalidError,
  PairingCodeUnusableError,
  PinLockedError,
  PinRejectedError,
  featureNotEnabled,
} from '../contracts/errors';
import type { StaffMember } from '../contracts/staff';
import type {
  DeviceEnrolment,
  EnrolDeviceCommand,
  EnrolledDevice,
  PairPhoneCommand,
  PhonePairing,
  PhonePairingPreview,
  PinSignInCommand,
  StaffRosterEntry,
  StaffSignInResult,
} from '../contracts/staffAuth';
import { normalizeEnrolmentCode } from '../contracts/staffAuth';
import { UnauthorizedError } from '../errors';
import { mockBranchFeatures } from './branchFeaturesMock';
import { mockRegistry, type MockRegistry } from './mockRegistry';
import { MOCK_STAFF_PIN, fixtureStaffFor } from './staffFixture';
import { mockRosterShiftsAround, mockStaffRoster } from './staffRosterMock';
import { mockVenues } from './venues';

/**
 * `/api/auth/staff/*` without a server, so the tablet's sign-in is walkable
 * in mock mode: the enrolment screen takes a code the console mock generated,
 * the keypad shows the branch's roster, and "Tap to sign out" locks the
 * tablet (QA F13). Before this the mock had no tablet session at all, the dev
 * role switcher stood in for it, and three screens could not be reached.
 *
 * Codes and devices live in the shared {@link MockRegistry}, because the code
 * is generated by one gateway (the console's) and redeemed by another (this
 * one), usually after a reload.
 */

const URL_TAG = 'mock://yalla/api/auth/staff';

/** AuthOptions.PinMaxAttempts and PinLockoutMinutes: five in a row, fifteen minutes. */
const PIN_MAX_ATTEMPTS = 5;
const PIN_LOCK_MS = 15 * 60_000;
const SESSION_SECONDS = 900;

export interface StaffAuthMockOptions {
  readonly registry?: MockRegistry | undefined;
  readonly now?: (() => Date) | undefined;
  /** The people a branch's roster is read from. Defaults to the fixture's. */
  readonly staff?: ((venueId: string) => readonly StaffMember[]) | undefined;
}

export function createMockStaffAuth(options: StaffAuthMockOptions = {}): StaffAuth {
  const registry = options.registry ?? mockRegistry;
  const now = options.now ?? (() => new Date());
  let sequence = 0;
  /**
   * staffMemberId → consecutive misses and the lockout they caused, as
   * `StaffMember.PinFailedAttempts` and `PinLockedUntilUtc` are on the server.
   */
  const pinState = new Map<string, { attempts: number; lockedUntil: number | null }>();

  function locate(branchId: string) {
    for (const venue of mockVenues) {
      const branch = venue.branches.find((candidate) => candidate.id === branchId);
      if (branch) return { venue, branch };
    }
    return null;
  }

  function staffOf(venueId: string): readonly StaffMember[] {
    if (options.staff) return options.staff(venueId);
    const venue = mockVenues.find((candidate) => candidate.id === venueId);
    return venue ? fixtureStaffFor(venue.id, venue.name, venue.branches) : [];
  }

  function device(deviceToken: string) {
    const found = registry.devices.get(deviceToken);
    if (!found || found.revokedAtUtc !== null) {
      throw new DeviceRevokedError({ url: `${URL_TAG}/device` });
    }
    const located = locate(found.branchId);
    if (!located) throw new DeviceRevokedError({ url: `${URL_TAG}/device` });
    return { ...found, ...located };
  }

  /** The PIN as `StaffAuthService` checks it, with the five-miss lockout. */
  function checkPin(member: StaffMember, pin: string, url: string): void {
    const t = now().getTime();
    const state = pinState.get(member.id) ?? { attempts: 0, lockedUntil: null };
    if (member.isPinLocked) {
      // The fixture's person a manager has yet to unlock: no known end.
      throw new PinLockedError({ url, lockedUntilUtc: null });
    }
    if (state.lockedUntil !== null && t < state.lockedUntil) {
      throw new PinLockedError({
        url,
        lockedUntilUtc: new Date(state.lockedUntil).toISOString(),
      });
    }

    if (pin !== MOCK_STAFF_PIN) {
      // StaffMember.RecordFailedPin: the miss that reaches the threshold is
      // the lockout itself.
      state.attempts += 1;
      pinState.set(member.id, state);
      if (state.attempts >= PIN_MAX_ATTEMPTS) {
        state.lockedUntil = t + PIN_LOCK_MS;
        throw new PinLockedError({
          url,
          lockedUntilUtc: new Date(state.lockedUntil).toISOString(),
        });
      }
      throw new PinRejectedError({ url });
    }

    pinState.delete(member.id);
  }

  /** A phone's person: the only one its roster lists and its PIN takes. */
  function boundOf(found: {
    readonly kind?: string | undefined;
    readonly boundStaffMemberId?: string | null | undefined;
  }): string | null {
    return found.kind === 'phone' ? (found.boundStaffMemberId ?? null) : null;
  }

  function boundMember(found: {
    readonly kind?: string | undefined;
    readonly boundStaffMemberId?: string | null | undefined;
    readonly venue: { readonly id: string };
  }) {
    const bound = boundOf(found);
    const member = bound
      ? staffOf(found.venue.id).find((person) => person.id === bound)
      : undefined;
    return member
      ? { id: member.id, fullName: member.fullName, role: staffRoleToUserRole(member.role) }
      : null;
  }

  /** Every PIN sign-in and renewal moves the console's "last seen". */
  function seen(deviceToken: string): void {
    const found = registry.devices.get(deviceToken);
    if (found) registry.devices.set(deviceToken, { ...found, lastSeenAtUtc: now().toISOString() });
  }

  /**
   * A pairing code as `FindPairingCodeAsync` judges it: unknown is 401
   * invalid, used is the 409, past its ten minutes or replaced is 401 expired.
   */
  function pairingFor(raw: string, url: string) {
    const code = normalizeEnrolmentCode(raw);
    const found = registry.phonePairings.get(code);
    if (!found) throw new PairingCodeInvalidError({ url });
    if (found.redeemedAtUtc !== null) throw new PairingCodeUnusableError({ url });
    if (found.supersededAtUtc !== null || Date.parse(found.expiresAtUtc) <= now().getTime()) {
      throw new PairingCodeExpiredError({ url });
    }
    const located = locate(found.branchId);
    const member = located
      ? staffOf(located.venue.id).find((person) => person.id === found.staffMemberId)
      : undefined;
    if (
      !located ||
      !member ||
      !member.isActive ||
      (member.branchId !== null && member.branchId !== found.branchId)
    ) {
      throw new PairingCodeUnusableError({ url });
    }
    if (member.role === 'kitchen') throw new KitchenPhoneNotAllowedError({ url });
    return { code, pairing: found, member, ...located };
  }

  /** Staff phones are a feature: off at the branch, a phone neither pairs nor signs in. */
  function refusePhoneOff(branchId: string, url: string): void {
    if (!mockBranchFeatures(registry, branchId).includes('staffPhone')) {
      throw featureNotEnabled(url, 'staffPhone', branchId);
    }
  }

  function session(deviceToken: string, member: StaffMember): StaffSignInResult {
    sequence += 1;
    const branchId = registry.devices.get(deviceToken)?.branchId ?? '';
    const renewalToken = `mockrenew_${member.id}_${sequence}`;
    registry.staffHandles.set(renewalToken, {
      renewalToken,
      deviceToken,
      staffMemberId: member.id,
    });
    return {
      identity: {
        staffMemberId: member.id,
        fullName: member.fullName,
        role: staffRoleToUserRole(member.role),
        branchId,
        // Read again on every renewal, as the server's is.
        features: mockBranchFeatures(registry, branchId),
      },
      tokens: {
        accessToken: `mockstaff_${member.id}_${sequence}`,
        renewalToken,
        expiresInSeconds: SESSION_SECONDS,
      },
    };
  }

  return {
    async enrol(command: EnrolDeviceCommand): Promise<DeviceEnrolment> {
      const code = normalizeEnrolmentCode(command.code);
      const found = registry.enrolmentCodes.get(code);
      // StaffAuthService.EnrolAsync's order: unknown is 401, spent is the
      // 409 whatever the date, and only then past its day is 401.
      if (!found) {
        throw new UnauthorizedError({ url: `${URL_TAG}/enrol` });
      }
      if (found.spentAtUtc !== null) {
        throw new EnrolmentCodeSpentError({ url: `${URL_TAG}/enrol` });
      }
      if (Date.parse(found.expiresAtUtc) <= now().getTime()) {
        throw new EnrolmentCodeExpiredError({ url: `${URL_TAG}/enrol` });
      }
      const at = now().toISOString();
      registry.enrolmentCodes.set(code, { ...found, spentAtUtc: at });
      const deviceToken = `mockdev_${command.deviceId}`;
      registry.devices.set(deviceToken, {
        deviceToken,
        deviceId: command.deviceId,
        deviceName: command.deviceName,
        branchId: found.branchId,
        enrolledAtUtc: at,
        revokedAtUtc: null,
      });
      return {
        deviceId: command.deviceId,
        deviceName: command.deviceName,
        branchId: found.branchId,
        deviceToken,
        expiresAtUtc: new Date(now().getTime() + 365 * 24 * 60 * 60_000).toISOString(),
      };
    },

    async getDevice(deviceToken: string): Promise<EnrolledDevice> {
      const found = device(deviceToken);
      return {
        deviceId: found.deviceId,
        deviceName: found.deviceName,
        branchId: found.branchId,
        branchName: found.branch.name,
        venueName: found.venue.name,
        enrolledAtUtc: found.enrolledAtUtc,
        lastSeenAtUtc: now().toISOString(),
        kind: found.kind ?? 'tablet',
        boundStaffMember: boundMember(found),
        features: mockBranchFeatures(registry, found.branchId),
      };
    },

    async previewPhonePairing(code: string): Promise<PhonePairingPreview> {
      const { pairing, member, venue, branch } = pairingFor(code, `${URL_TAG}/phone-pair/preview`);
      return {
        staffMemberId: member.id,
        fullName: member.fullName,
        role: staffRoleToUserRole(member.role),
        branchId: branch.id,
        branchName: branch.name,
        venueName: venue.name,
        expiresAtUtc: pairing.expiresAtUtc,
      };
    },

    async pairPhone(command: PairPhoneCommand): Promise<PhonePairing> {
      const url = `${URL_TAG}/phone-pair`;
      const { code, pairing, member } = pairingFor(command.code, url);
      const deviceToken = `mockdev_${command.clientDeviceId}`;
      const existing = registry.devices.get(deviceToken);
      // A browser that is one of the branch's live tablets is refused: a
      // manager revokes the tablet first.
      if (existing && existing.revokedAtUtc === null && (existing.kind ?? 'tablet') === 'tablet') {
        throw new PairingCodeUnusableError({ url });
      }
      refusePhoneOff(pairing.branchId, url);
      // The PIN check is the PIN screen's, lockout included; a wrong one
      // leaves the code usable.
      checkPin(member, command.pin, url);
      const at = now().toISOString();
      registry.phonePairings.set(code, { ...pairing, redeemedAtUtc: at });
      registry.devices.set(deviceToken, {
        deviceToken,
        deviceId: command.clientDeviceId,
        deviceName: command.deviceName,
        branchId: pairing.branchId,
        enrolledAtUtc: at,
        revokedAtUtc: null,
        kind: 'phone',
        boundStaffMemberId: member.id,
        lastSeenAtUtc: at,
        platform: command.platform ?? null,
        browser: command.browser ?? null,
      });
      return {
        device: {
          deviceId: command.clientDeviceId,
          deviceName: command.deviceName,
          branchId: pairing.branchId,
          deviceToken,
          expiresAtUtc: new Date(now().getTime() + 365 * 24 * 60 * 60_000).toISOString(),
        },
        session: session(deviceToken, member),
      };
    },

    async getRoster(deviceToken: string): Promise<readonly StaffRosterEntry[]> {
      const found = device(deviceToken);
      const bound = boundOf(found);
      // A phone lists its own person alone.
      const people = staffOf(found.venue.id).filter(
        (person) => bound === null || person.id === bound,
      );
      const at = now();
      return mockStaffRoster(
        people,
        { venueId: found.venue.id, branchId: found.branchId },
        {
          now: at,
          timeZone: found.branch.timeZoneId,
          shifts: mockRosterShiftsAround(people, found.branchId, at),
        },
      );
    },

    async signInWithPin(deviceToken: string, command: PinSignInCommand) {
      const found = device(deviceToken);
      const url = `${URL_TAG}/pin`;
      const member = staffOf(found.venue.id).find((person) => person.id === command.staffMemberId);
      const bound = boundOf(found);
      // Somebody who does not sign in on this tablet does not exist as far as
      // it is concerned: rejected, and no miss counted against anybody. On a
      // phone that is everybody but its own person.
      if (
        (bound !== null && command.staffMemberId !== bound) ||
        !member ||
        !member.isActive ||
        (member.branchId !== null && member.branchId !== found.branchId)
      ) {
        throw new PinRejectedError({ url });
      }

      if (found.kind === 'phone') refusePhoneOff(found.branchId, url);
      checkPin(member, command.pin, url);
      seen(deviceToken);
      return session(deviceToken, member);
    },

    async renew(renewalToken: string): Promise<StaffSignInResult | null> {
      const handle = registry.staffHandles.get(renewalToken);
      if (!handle) return null;
      // Rotated on every use, as the server's is.
      registry.staffHandles.delete(renewalToken);
      let found;
      try {
        found = device(handle.deviceToken);
      } catch (error) {
        if (error instanceof DeviceRevokedError) throw error;
        return null;
      }
      const member = staffOf(found.venue.id).find((person) => person.id === handle.staffMemberId);
      if (!member) return null;
      seen(handle.deviceToken);
      return session(handle.deviceToken, member);
    },

    async signOut(renewalToken: string): Promise<void> {
      registry.staffHandles.delete(renewalToken);
    },
  };
}
